import { test, expect } from '../lib/mock-fixtures';
import { WorkspacePage } from '../lib/pages/WorkspacePage';
import { PROJECT_ID, project } from '../lib/mocks/application';
import { buildSystemPrompt, ProjectContextSchema, StreamRequestSchema } from '@devdocs/shared';
import { readSavedInterviewData } from '../../lib/interview/snapshot';

test('creation stays in setup until valid answers start the interview', async ({ page, app }, info) => {
  test.setTimeout(120_000);
  app.projects = [];
  const ui = new WorkspacePage(page, info);
  await ui.goto('/dashboard'); await ui.click(/New project/i);
  await ui.fill('e.g. TaskFlow SaaS', '   '); await ui.click(/SaaS product$/);
  await expect(ui.text('Enter a project name.')).toBeVisible();
  await expect(ui.button(/Create project/)).toBeDisabled();
  await ui.fill('e.g. TaskFlow SaaS', 'Setup project');
  await ui.click(/SaaS product$/);
  // Two synchronous clicks exercise the submission guard before a render.
  await ui.button(/Create project/).evaluate(button => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click(); });
  await ui.waitForDiscovery();
  expect(app.calls.filter(c => c.procedure === 'projects.create')).toHaveLength(1);
  expect(app.streams).toHaveLength(0);
  await expect(ui.text('Project setup')).toBeVisible();
  await expect(ui.text('0%')).toHaveCount(0);
  await expect(ui.button(/Start interview/)).toBeDisabled();
  await ui.expectViewportFits();
  await page.screenshot({ path: info.outputPath('project-setup.png') });
  const team = page.getByRole('group', { name: 'Development team size' });
  await expect(team.getByRole('button')).toHaveText(['Just me', '2–3 people', '4–10 people', '11+ people']);
  const timeline = page.getByRole('group', { name: 'Timeline to launch' });
  await expect(timeline.getByRole('button')).toHaveText(['Less than 1 month', '1 to under 3 months', '3 to under 6 months', '6 months or more', 'Not sure yet']);
  await team.getByRole('button').first().focus();
  await timeline.getByRole('button').first().focus();
  await expect(team).toContainText('Select an answer to continue.');
  await team.getByRole('button', { name: '11+ people', exact: true }).click();
  await expect(team.getByRole('button', { name: '11+ people', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(team).not.toContainText('Select an answer to continue.');
  await timeline.getByRole('button', { name: 'Not sure yet', exact: true }).click();
  await page.getByRole('group', { name: 'Project funding' }).getByRole('button', { name: 'Not sure yet', exact: true }).click();
  await expect(ui.button(/Start interview/)).toBeDisabled();
  await ui.click('Intermediate'); await ui.click(/Start interview/);
  await ui.waitForInterview();
  await expect(ui.text('Project setup')).toHaveCount(0);
  await expect(page.locator('header')).toContainText('Documentation');
  await expect.poll(() => app.projects[0].interviewData?.lockedContext?.budget).toBe('not_sure');
  expect(app.projects[0].interviewData.lockedContext.timeline).toBe('not_sure');
  expect(app.projects[0].interviewData.lockedContext.teamSize).toBe('eleven_plus');
  await ui.reload(); await ui.waitForInterview();
  await ui.answer('A collaboration workspace for remote teams');
  await expect.poll(() => app.streams.length).toBeGreaterThan(0);
  const request = StreamRequestSchema.parse(app.streams[0]);
  expect(request.interview!.lockedContext.budget).toBe('not_sure');
  expect(request.interview!.lockedContext.timeline).toBe('not_sure');
  const prompt = buildSystemPrompt(request.interview!.lockedContext, 'planning', '', {});
  expect(prompt).toContain('Project funding: Not sure yet (unresolved)');
  expect(prompt).toContain('Timeline to launch: Not sure yet (unresolved)');
  await ui.expectViewportFits();
  await page.screenshot({ path: info.outputPath('started-interview.png') });
});

test('saved legacy ranges resume without changing their meaning', async ({ page, app }, info) => {
  const legacy = project();
  legacy.interviewData.lockedContext.teamSize = 'large';
  legacy.interviewData.lockedContext.timeline = '3_6_months';
  app.projects = [legacy];
  const saved = readSavedInterviewData(legacy.interviewData)!;
  expect(saved.lockedContext).toEqual(legacy.interviewData.lockedContext);
  expect(ProjectContextSchema.parse(saved.lockedContext)).toEqual(legacy.interviewData.lockedContext);
  const ui = new WorkspacePage(page, info);
  await ui.openProject(PROJECT_ID); await ui.waitForInterview();
  await expect(page.getByRole('group', { name: 'Project context', exact: true })).toHaveCount(0);
  await ui.expectViewportFits();
  await ui.answer('A planning workspace for remote teams');
  await expect.poll(() => app.streams.length).toBeGreaterThan(0);
  expect(app.streams[0].interview.lockedContext).toEqual(saved.lockedContext);
});
